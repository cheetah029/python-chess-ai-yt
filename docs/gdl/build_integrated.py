"""Build docs/gdl/integrated.gdl — the OFFICIAL game description.

The official dialect for this project is **infix HRF**
(ggp.stanford.edu / Epilog style):

    legal(P, move(boulder, FF, FR, TF, TR)) :- true(control(P)) & ...

Prefix KIF — `(<= (legal ?p (move boulder ...)) ...)` — is an
OUTDATED dialect. It is hard to read and is retained only as a
generated compatibility artifact in `integrated_prefix.gdl`, because
the 11 step fragments are still authored in it. Nobody should read
the prefix file, and no documentation should quote it. Every example,
every explanation and every LGREF input uses the infix file.

This script reads the legacy prefix `integrated_prefix.gdl` (produced
from the step fragments by `build_integrated_prefix.py`) and converts
it via `src/ggp/infix.py`.

After changing ANY step file, re-run BOTH scripts, in this order, so
the two files stay consistent (issue #190):

    python3 docs/gdl/build_integrated_prefix.py > docs/gdl/integrated_prefix.gdl
    python3 docs/gdl/build_integrated.py

`tests/test_gdl_dialect_consistency.py` fails the build if they drift.
"""

import os
import sys

sys.path.insert(0, os.path.join(
    os.path.dirname(__file__), '..', '..', 'src'))

from ggp.infix import convert_text

HERE = os.path.dirname(__file__)
PREFIX_PATH = os.path.join(HERE, 'integrated_prefix.gdl')
INFIX_PATH = os.path.join(HERE, 'integrated.gdl')

HEADER = """\
============================================================
INTEGRATED GDL — THE OFFICIAL DESCRIPTION OF THIS GAME.

Dialect: infix HRF (ggp.stanford.edu / Epilog). This is the
dialect to read, to quote in documentation, and to feed to the
LGREF framework.

The prefix-KIF file integrated_prefix.gdl says exactly the same
thing in an OUTDATED dialect that is hard to read. Ignore it.
It survives only because the 11 step fragments are still
authored in prefix and some older tooling reads them.

Generated by docs/gdl/build_integrated.py from
integrated_prefix.gdl. Do not edit by hand — edit the step files
and re-run both build scripts (issue #190):

    python3 docs/gdl/build_integrated_prefix.py > docs/gdl/integrated_prefix.gdl
    python3 docs/gdl/build_integrated.py

Conversion notes (both semantics-preserving):
- (or A B) bodies were expanded into one rule per branch, so this
  file has MORE statements than the prefix one (522 vs 488). Each
  branch is a separate rule here, which is the finer and more
  honest reading.
- (= ?x c) conjuncts were resolved by constant substitution.
============================================================\
"""


def main():
    with open(PREFIX_PATH) as f:
        prefix_text = f.read()
    infix_text = convert_text(prefix_text, header_comment=HEADER)
    with open(INFIX_PATH, 'w') as f:
        f.write(infix_text)
    n_statements = sum(
        1 for line in infix_text.splitlines()
        if line.strip() and not line.strip().startswith('%'))
    print(f'wrote {INFIX_PATH}: {n_statements} statements')


if __name__ == '__main__':
    main()
