"""Krieg-m,n,k: the hidden-information twin of every m,n,k row (#294).

Krieg-TicTacToe (`kriegtictactoe.gdl`, #286) is m,n,k at 3,3,3 with the
opponent's marks hidden. This writes the same game for any board, so
each perfect-information m,n,k row can have a twin that differs ONLY in
what a player is told; the gap between the two is then the cost of
hidden information at that size.

THE RULES, unchanged from Krieg-TicTacToe. An m-by-n board, k in a row
(horizontally, vertically or diagonally) wins, xplayer moves first.
Neither player sees the other's marks. After its own move a player is
told only `ok` (the cell was empty and is now its own) or `taken` (the
opponent already holds it). A failed mark uses up the turn, so control
alternates strictly, and a cell found taken may not be tried again.
Legality reads only control, the player's own marks and the cells it
has learned are taken, so the game is well-formed for GDL-II.

WHY GENERATED. Each winning line is written out as its own rule, one
ground lookup per cell. A recursive "k in a row" relation would be
shorter, but explicit lines are what a bottom-up reasoner evaluates
fastest, and they make the description's meaning checkable line by
line against `lines()` below.

`python -m lgref.identify.testgames.kriegmnk M N K > FILE` writes one;
`kriegmnk_5_5_4.gdl` is checked in, and `test_kriegmnk.py` fails if it
drifts from what this module writes.
"""

HEADER = """\
% ============================================================
% Krieg-m,n,k {m},{n},{k} -- GDL-II test game, infix HRF (#294).
%
% GENERATED by lgref/identify/testgames/kriegmnk.py; do not edit.
%
% {m}x{n} board, {k} in a row wins, xplayer first. Neither player sees
% the other's marks. After its own move a player is told only `ok`
% (the cell was empty and is now its own) or `taken` (the opponent
% holds it). A failed mark uses up the turn, so control alternates
% strictly; a cell found taken may not be tried again.
%
% It is the m,n,k {m},{n},{k} row with only the information changed.
% NOT in `ground_truth.GAMES`: a playing benchmark, not an
% identification gate.
% ============================================================
"""

RULES = (
    "init(control(xplayer))\n"
    "legal(P,mark(M,N)) :- true(control(P)) & true(cell(M,N,W)) & "
    "symbol(P,S) & distinct(W,S) & ~true(tried(P,M,N))\n"
    """\
legal(xplayer,noop) :- true(control(oplayer))
legal(oplayer,noop) :- true(control(xplayer))
sees(P,ok) :- does(P,mark(M,N)) & true(cell(M,N,b))
sees(P,taken) :- does(P,mark(M,N)) & ~true(cell(M,N,b))
attempted(M,N) :- does(P,mark(M,N))
next(cell(M,N,S)) :- does(P,mark(M,N)) & true(cell(M,N,b)) & symbol(P,S)
next(cell(M,N,W)) :- true(cell(M,N,W)) & distinct(W,b)
next(cell(M,N,b)) :- true(cell(M,N,b)) & ~attempted(M,N)
next(tried(P,M,N)) :- does(P,mark(M,N)) & ~true(cell(M,N,b))
next(tried(P,M,N)) :- true(tried(P,M,N))
next(control(xplayer)) :- true(control(oplayer))
next(control(oplayer)) :- true(control(xplayer))
open :- true(cell(M,N,b))
terminal :- line(x)
terminal :- line(o)
terminal :- ~open
goal(xplayer,100) :- line(x)
goal(xplayer,0) :- line(o)
goal(xplayer,50) :- ~line(x) & ~line(o)
goal(oplayer,100) :- line(o)
goal(oplayer,0) :- line(x)
goal(oplayer,50) :- ~line(x) & ~line(o)
""")

DIRECTIONS = ((0, 1), (1, 0), (1, 1), (1, -1))


def lines(m, n, k):
    """Every winning line, as a tuple of k (row, column) cells, 1-based."""
    out = []
    for row in range(1, m + 1):
        for col in range(1, n + 1):
            for dr, dc in DIRECTIONS:
                cells = tuple((row + i * dr, col + i * dc) for i in range(k))
                if all(1 <= r <= m and 1 <= c <= n for r, c in cells):
                    out.append(cells)
    return out


def generate(m, n, k):
    """The infix GDL-II text of Krieg-m,n,k."""
    if not (1 <= k <= max(m, n)):
        raise ValueError('k must be between 1 and the longer side')
    parts = [HEADER.format(m=m, n=n, k=k),
             'role(xplayer)\nrole(oplayer)\n',
             'symbol(xplayer,x)\nsymbol(oplayer,o)\n']
    parts.append(''.join('init(cell({0},{1},b))\n'.format(r, c)
                         for r in range(1, m + 1) for c in range(1, n + 1)))
    parts.append(RULES)
    for cells in lines(m, n, k):
        body = ' & '.join('true(cell({0},{1},W))'.format(r, c)
                          for r, c in cells)
        parts.append('line(W) :- {0} & distinct(W,b)\n'.format(body))
    return ''.join(parts)


def main(argv=None):
    import sys

    args = list(sys.argv[1:] if argv is None else argv)
    sys.stdout.write(generate(*(int(a) for a in args)))


if __name__ == '__main__':
    main()
